# Builds the parry effect graphics (original artwork) as 4bpp GBA tiles.
import sys, math
W=0; WH=1; YL=2; OR=3; DK=4; CY=5; BL=6
# palette (BGR555) for OBJ palette 15
def rgb(r,g,b): return (r>>3)|((g>>3)<<5)|((b>>3)<<10)
pal=[0, rgb(255,255,255), rgb(255,240,140), rgb(255,160,40), rgb(24,24,48), rgb(140,230,255), rgb(60,120,255)]+[0]*9

# 16x16 starburst spark
spark=[[0]*16 for _ in range(16)]
cx=cy=7.5
for y in range(16):
    for x in range(16):
        dx,dy=x-cx,y-cy; r=math.hypot(dx,dy); a=math.atan2(dy,dx)
        ray=abs(math.cos(4*a))**6   # 8 rays
        lim=2.2+5.6*ray
        if r<1.6: spark[y][x]=WH
        elif r<lim*0.55: spark[y][x]=WH if ray>0.5 else YL
        elif r<lim*0.8: spark[y][x]=YL
        elif r<lim: spark[y][x]=OR

# 8x8 pixel font (own design), 5x7 glyphs
F={
'P':["11110","10001","10001","11110","10000","10000","10000"],
'A':["01110","10001","10001","11111","10001","10001","10001"],
'R':["11110","10001","10001","11110","10100","10010","10001"],
'Y':["10001","10001","01010","00100","00100","00100","00100"],
'!':["00100","00100","00100","00100","00100","00000","00100"],
'C':["01111","10000","10000","10000","10000","10000","01111"],
'O':["01110","10001","10001","10001","10001","10001","01110"],
'U':["10001","10001","10001","10001","10001","10001","01110"],
'N':["10001","11001","10101","10011","10001","10001","10001"],
'T':["11111","00100","00100","00100","00100","00100","00100"],
'E':["11111","10000","10000","11110","10000","10000","11111"],
' ':["00000"]*7,
}
def text_strip(t, fill, edge):
    # returns 8 rows x (8*len) pixels; glyph with dark outline
    w=8*len(t); img=[[0]*w for _ in range(8)]
    for i,ch in enumerate(t):
        g=F[ch]
        for y in range(7):
            for x in range(5):
                if g[y][x]=='1':
                    px,py=i*8+1+x,y
                    img[py][px]=fill
    # outline
    out=[r[:] for r in img]
    for y in range(8):
        for x in range(w):
            if img[y][x]==0:
                for dx,dy in ((1,0),(-1,0),(0,1),(0,-1)):
                    xx,yy=x+dx,y+dy
                    if 0<=xx<w and 0<=yy<8 and img[yy][xx] not in (0,):
                        out[y][x]=edge; break
    return out
def tiles_from(img, tw, th):
    res=[]
    for ty in range(th):
        for tx in range(tw):
            t=[]
            for y in range(8):
                row=img[ty*8+y]
                for x in range(0,8,2):
                    a=row[tx*8+x]; b=row[tx*8+x+1]
                    t.append(a|(b<<4))
            res.append(bytes(t))
    return res
sp=tiles_from(spark,2,2)              # 4 tiles: TL TR BL BR
parry=tiles_from(text_strip("PARRY!  ",YL,DK),8,1)   # 8 tiles
counter=tiles_from(text_strip("COUNTER!",CY,DK),8,1) # 8 tiles
# VRAM layout (2D mapping, 32 tiles per row): row30 cols17..26, row31 cols17..26
row30=[sp[0],sp[1]]+parry      # 10 tiles
row31=[sp[2],sp[3]]+counter    # 10 tiles
def carr(name,data): return 'static CONST_DATA u8 %s[] __attribute__((aligned(4))) = {\n%s\n};\n'%(name,',\n'.join(', '.join('0x%02X'%b for b in data[i:i+16]) for i in range(0,len(data),16)))
out='// generated by mkgfx.py: original parry effect artwork (spark burst, pixel-font text)\n'
out+=carr('gParryGfxRow30',b''.join(row30))+carr('gParryGfxRow31',b''.join(row31))
out+='static CONST_DATA u16 gParryGfxPal[16] = { %s };\n'%', '.join('0x%04X'%c for c in pal)
open(sys.argv[1],'w').write(out)
# preview
from PIL import Image
pv=Image.new('RGB',(80,16))
pr=[(0,0,0),(255,255,255),(255,240,140),(255,160,40),(24,24,48),(140,230,255),(60,120,255)]+[(0,0,0)]*9
for r,row in enumerate((row30,row31)):
    for i,t in enumerate(row):
        for y in range(8):
            for x in range(8):
                b=t[y*4+x//2]; v=(b>>4) if x&1 else b&15
                pv.putpixel((i*8+x,r*8+y),pr[v])
pv.resize((640,128),Image.NEAREST).save(sys.argv[2])
