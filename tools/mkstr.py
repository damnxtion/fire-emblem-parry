import sys
m={}
for s,c0 in [("2A3B4C5D6EFuGvHwIxJy",0x9F),("KzL",0xB3),("M N!O\"P#Q$7R%S&T",0xB7),("'UVWXYZ(-a).b*/c+0d,",0xC7),("1efghi8j9k:lmnopq",0xDB)]:
    for i,ch in enumerate(s): m[ch]=0x8200+c0+i
m['r']=0x82ED; m['s']=0x82F0; m['t']=0x82F1
strs={
 'STR_INCOMING':"Enemy attack incoming!",
 'STR_BOSS':"Boss technique incoming!",
 'STR_KEYS':"A: Parry   B: Dodge",
 'STR_PARRY':"PARRY!",
 'STR_RIPOSTE':"Riposte: next blow can't miss",
 'STR_DODGE':"DODGE!",
 'STR_DODGE2':"The attack misses",
 'STR_FAIL':"Too slow...",
 'STR_FAIL2':"The enemy strikes normally",
}
out=[]
for k,v in strs.items():
    bs=[]
    for ch in v:
        if ch=="'": ch="'"
        c=m[ch]; bs+= [c>>8, c&0xFF]
    bs.append(0)
    out.append('static CONST_DATA char %s[] = { %s };'%(k,', '.join('0x%02X'%x for x in bs)))
open(sys.argv[1],'w').write('// generated by mkstr.py (translation-patch glyph encoding)\n'+'\n'.join(out)+'\n')
